norm AS (
  SELECT lower(btrim(regexp_replace(lab_name, '\s+', ' ', 'g'))) AS lab_key,
         logged_at, actor_id, actor_name, actor_role
  FROM audit
),
creator AS (
  SELECT DISTINCT ON (lab_key)
         lab_key, actor_name, actor_role,
         count(*) OVER (PARTITION BY lab_key) - 1 AS retries
  FROM norm ORDER BY lab_key, logged_at
),
mapped AS (SELECT "labId" AS lab_id, min("assignedAt") AS first_mapped, count(*) AS stores
           FROM src."LabsOnStore" GROUP BY 1),
priced AS (SELECT "labId" AS lab_id, min("assignedAt") AS first_priced, count(*) AS packages
           FROM src."PackagesOnLab" GROUP BY 1),
dos    AS (SELECT lab_id, count(*) AS dos_tests, count(*) FILTER (WHERE active) AS dos_active,
                  count(*) FILTER (WHERE "inHouse") AS dos_in_house
           FROM src."DOS" GROUP BY 1),
ord    AS (SELECT "labId" AS lab_id, count(*) AS orders_total,
                  count(*) FILTER (WHERE "createdAt" >= now() - interval '90 days') AS orders_90d,
                  max("createdAt")::date AS last_order
           FROM src."Order" WHERE "labId" IS NOT NULL GROUP BY 1)
